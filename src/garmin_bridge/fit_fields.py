def event_payload_allowed(event, kind, value, *, short=False):
    return (
        type(kind) is int
        and 0 <= kind <= 9
        and event in EVENT_DATA_MAX
        and not (short and event in (33, 42, 43, 75))
        and (value is None or type(value) is int and 0 <= value <= EVENT_DATA_MAX[event])
    )
